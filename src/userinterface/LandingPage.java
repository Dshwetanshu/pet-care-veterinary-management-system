    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // TODO add your handling code here:

        // Get username
        String username = txtUserName.getText();

        // Get Password
        char[] passwordCharArray = txtPassword.getPassword();
        String password = String.valueOf(passwordCharArray);

        UserAccount account = ecosystem.getUserAccountDirectory().authenticateUser(username, password);

        Enterprise inEnterprise = null;
        Organization inOrg = null;

        if(account == null) {
            for(Network ns: ecosystem.getNetworks()) {
                for(Enterprise e : ns.getEnterpriseDirectory().getEnterpriseList()) {
                    account = e.getUserAccountDirectory().authenticateUser(username, password);
                    if(account == null) {
                        for(Organization org: e.getOrganizationDirectory().getOrganizations()) {
                            account = org.getUserAccountDirectory().authenticateUser(username, password);
                            if(account != null) {
                                inEnterprise = e;
                                inOrg = org;
                            }
                        }
                    } else {
                        inEnterprise = e;
                        break;
                    } if(inOrg != null) {
                        break;
                    }
                } if(inEnterprise != null) {
                    break;
                }
            }
        }

        // Set UI warnings
        if(account == null) {
            txtUserName.setBorder(BorderFactory.createLineBorder(Color.RED));
            txtPassword.setBorder(BorderFactory.createLineBorder(Color.RED));
            JOptionPane.showMessageDialog(null, "Invalid credentials!");
            return;
        } else {
            txtUserName.setBorder(BorderFactory.createLineBorder(Color.GRAY));
            txtPassword.setBorder(BorderFactory.createLineBorder(Color.GRAY));
            CardLayout layout = (CardLayout) leftJPanel.getLayout();
            leftJPanel.add("workArea",account.getRole().createWorkArea(leftJPanel, account, inOrg, inEnterprise, ecosystem));
            layout.next(leftJPanel);
        }

        // Disable features after successful login
        btnLogin.setEnabled(false);
        btnLogout.setEnabled(true);
        txtUserName.setEnabled(false);
        txtPassword.setEnabled(false);
    }//GEN-LAST:event_btnLoginActionPerformed

